let occSeq = 0
const perStandSeq = new Map<number, number>()
function occ(
  standId: number,
  range: [string, string],
  flight: string,
  model: string,
  level: OccupancyDoc['保障等级'],
): OccupancyDoc {
  const seq = (perStandSeq.get(standId) ?? 0) + 1
  perStandSeq.set(standId, seq)
  occSeq += 1
  return {
    id: `OCC-${standId}-${seq}`,
    standId,
    date: TODAY,
    startMin: hm(range[0]),
    endMin: hm(range[1]),
    航班号: flight,
    机型: model,
    保障等级: level,
    createdAt: Date.now() + occSeq,
  }
}

