function bridgeJob(
  id: number,
  bridgeNo: string,
  standCode: string,
  flight: string,
  occupancyId: string,
  dock: string,
  release: string,
  status = '待靠接',
): EntryRow {
  return {
    id,
    status,
    pending: status !== '已撤离',
    abnormal: false,
    作业编号: `BRID-${String(id).padStart(4, '0')}`,
    廊桥编号: bridgeNo,
    对应机位: standCode,
    航班号: flight,
    关联占用: occupancyId,
    靠桥时间: at(dock),
    撤桥时间: at(release),
    操作人员: '—',
    对接检查项: status === '待靠接' ? '待检查' : '已检查',
    作业状态: status,
  }
}

